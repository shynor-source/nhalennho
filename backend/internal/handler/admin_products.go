type optionValuePayload struct {
	Value         string `json:"value"`
	PriceDeltaVND *int64 `json:"priceDeltaVnd"`
}

type optionPayload struct {
	Kind   string               `json:"kind"`
	Values []optionValuePayload `json:"values"`
}

type productPayload struct {
	Name        string          `json:"name"`
	Description string          `json:"description"`
	CategoryID  *int64          `json:"categoryId"`
	PriceVND    int64           `json:"priceVnd"`
	PriceMaxVND *int64          `json:"priceMaxVnd"`
	Colors      []string        `json:"colors"`
	IsActive    bool            `json:"isActive"`
	ShopeeURL   string          `json:"shopeeUrl"`
	Options     []optionPayload `json:"options"`
	Images      []string        `json:"images"`
}

type validationError struct{ msg string }

func (e validationError) Error() string { return e.msg }
func errInvalid(msg string) error       { return validationError{msg} }

// toInput validates the writable fields. The slug is generated by the server
// from the product name, so the admin never has to type one.
func (p productPayload) toInput() (model.ProductInput, []model.ProductOption, error) {
	name := strings.TrimSpace(p.Name)
	if l := utf8.RuneCountInString(name); l < 1 || l > 200 {
		return model.ProductInput{}, nil, errInvalid("tên sản phẩm phải từ 1 đến 200 ký tự")
	}
	if utf8.RuneCountInString(p.Description) > 5000 {
		return model.ProductInput{}, nil, errInvalid("mô tả quá dài")
	}
	if p.PriceVND < 0 || p.PriceVND > 1_000_000_000_000 {
		return model.ProductInput{}, nil, errInvalid("giá không hợp lệ")
	}
	if p.PriceMaxVND != nil {
		if *p.PriceMaxVND < p.PriceVND || *p.PriceMaxVND > 1_000_000_000_000 {
			return model.ProductInput{}, nil, errInvalid("giá cao nhất phải lớn hơn hoặc bằng giá thấp nhất")
		}
	}
	colors := make([]string, 0, len(p.Colors))
	seen := map[string]bool{}
	for _, c := range p.Colors {
		c = strings.TrimSpace(c)
		if c == "" {
			continue
		}
		if utf8.RuneCountInString(c) > 40 {
			return model.ProductInput{}, nil, errInvalid("màu quá dài")
		}
		if !seen[c] {
			seen[c] = true
			colors = append(colors, c)
		}
	}
	if len(colors) > 12 {
		return model.ProductInput{}, nil, errInvalid("quá nhiều màu")
	}
	if len(p.Images) > 10 {
		return model.ProductInput{}, nil, errInvalid("tối đa 10 ảnh mỗi sản phẩm")
	}
	images := make([]string, 0, len(p.Images))
	seenImg := map[string]bool{}
	for _, img := range p.Images {
		img = strings.TrimSpace(img)
		if img == "" {
			continue
		}
		if !validMediaPath(img) {
			return model.ProductInput{}, nil, errInvalid("đường dẫn ảnh không hợp lệ")
		}
		if !seenImg[img] {
			seenImg[img] = true
			images = append(images, img)
		}
	}
	shopeeURL := strings.TrimSpace(p.ShopeeURL)
	if shopeeURL != "" {
		const maxLen = 512
		if l := utf8.RuneCountInString(shopeeURL); l > maxLen {
			return model.ProductInput{}, nil, errInvalid("link Shopee quá dài")
		}
		// Only official Shopee product/store URLs are accepted.
		const allowedHost = "shopee.vn"
		parsed, err := url.Parse(shopeeURL)
		if err != nil || parsed.Scheme != "https" ||
			(parsed.Hostname() != allowedHost && !strings.HasSuffix(parsed.Hostname(), "."+allowedHost)) {
			return model.ProductInput{}, nil, errInvalid("link Shopee không hợp lệ — phải là đường dẫn shopee.vn")
		}
	}
	if len(p.Options) > 4 {
		return model.ProductInput{}, nil, errInvalid("tối đa 4 đặc điểm mỗi sản phẩm")
	}
	opts := make([]model.ProductOption, 0, len(p.Options))
	for _, o := range p.Options {
		values := make([]model.ProductOptionValue, 0, len(o.Values))
		for _, v := range o.Values {
			values = append(values, model.ProductOptionValue{Value: v.Value, PriceDeltaVND: v.PriceDeltaVND})
		}
		opts = append(opts, model.ProductOption{Kind: o.Kind, Values: values})
	}
	validated, verr := repository.ValidateProductOptions(opts)
	if verr != nil {
		return model.ProductInput{}, nil, verr
	}
	return model.ProductInput{
		Name:        name,
		Description: strings.TrimSpace(p.Description),
		CategoryID:  p.CategoryID,
		PriceVND:    p.PriceVND,
		PriceMaxVND: p.PriceMaxVND,
		Colors:      colors,
		IsActive:    p.IsActive,
		ShopeeURL:   shopeeURL,
		Images:      images,
	}, validated, nil
}

func (s *Server) uniqueProductSlug(ctx context.Context, base string, excludeID int64) (string, error) {
	candidate := base
	for i := 2; i <= 200; i++ {
		taken, err := s.db.ProductSlugExists(ctx, candidate, excludeID)
		if err != nil {
			return "", err
		}
		if !taken {
			return candidate, nil
		}
		candidate = fmt.Sprintf("%s-%d", base, i)
	}
	return "", errors.New("could not allocate a unique slug")
}

func (s *Server) adminListProducts(w http.ResponseWriter, r *http.Request) {
	q := r.URL.Query()
	page := parsePositiveInt(q.Get("page"), 1)
	perPage := parsePositiveInt(q.Get("per_page"), 20)
	if perPage > 100 {
		perPage = 100
	}
	filter := model.ProductFilter{
		Query:      strings.TrimSpace(q.Get("q")),
		ActiveOnly: false,
		Sort:       "newest",
		Limit:      perPage,
		Offset:     (page - 1) * perPage,
	}
	if len(filter.Query) > 100 {
		writeError(w, http.StatusBadRequest, "từ khóa quá dài")
		return
	}
	items, err := s.db.ListProducts(r.Context(), filter)
	if err != nil {
		s.serverError(w, err)
		return
	}
	total, err := s.db.CountProducts(r.Context(), filter)
	if err != nil {
		s.serverError(w, err)
		return
	}
	out := make([]productDTO, 0, len(items))
	for _, p := range items {
		out = append(out, toProductDTO(p))
	}
	writeJSON(w, http.StatusOK, map[string]any{"items": out, "total": total, "page": page, "perPage": perPage})
}

func (s *Server) adminGetProduct(w http.ResponseWriter, r *http.Request) {
	id, ok := pathID(r, "id")
	if !ok {
		writeError(w, http.StatusBadRequest, "id không hợp lệ")
		return
	}
	product, err := s.db.GetProductByID(r.Context(), id)
	if errors.Is(err, repository.ErrNotFound) {
		writeError(w, http.StatusNotFound, "không tìm thấy sản phẩm")
		return
	}
	if err != nil {
		s.serverError(w, err)
		return
	}

	if err := s.db.AttachOptions(r.Context(), product); err != nil {
		s.serverError(w, err)
		return
	}
	images, err := s.db.ListProductImages(r.Context(), product.ID)
	if err != nil {
		s.serverError(w, err)
		return
	}
	dto := toProductDTO(*product)
	dto.Images = images
	writeJSON(w, http.StatusOK, dto)
}

func (s *Server) adminCreateProduct(w http.ResponseWriter, r *http.Request) {
	var payload productPayload
	if !readJSON(w, r, &payload, s.cfg.MaxRequestBody) {
		return
	}
	in, opts, err := payload.toInput()
	if err != nil {
		writeError(w, http.StatusBadRequest, err.Error())
		return
	}
	valid, err := s.categoryExists(r, in.CategoryID)
	if err != nil {
		s.serverError(w, err)
		return
	}
	if !valid {
		writeError(w, http.StatusBadRequest, "danh mục không tồn tại")
		return
	}

	in.Slug, err = s.uniqueProductSlug(r.Context(), slug.Make(in.Name, "san-pham"), 0)
	if err != nil {
		s.serverError(w, err)
		return
	}

	product, err := s.db.CreateProduct(r.Context(), in)
	if err != nil {
		s.serverError(w, err)
		return
	}
	if _, err := s.db.ReplaceProductImages(r.Context(), product.ID, in.Images); err != nil {
		s.serverError(w, err)
		return
	}
	if err := s.db.SaveProductOptions(r.Context(), product.ID, opts); err != nil {
		s.serverError(w, err)
		return
	}
	dto := toProductDTO(*product)
	dto.Images = in.Images
	dto.CoverImage = ""
	if len(in.Images) > 0 {
		dto.CoverImage = in.Images[0]
	}
	writeJSON(w, http.StatusCreated, dto)
}

func (s *Server) adminUpdateProduct(w http.ResponseWriter, r *http.Request) {
	id, ok := pathID(r, "id")
	if !ok {
		writeError(w, http.StatusBadRequest, "id không hợp lệ")
		return
	}
	existing, err := s.db.GetProductByID(r.Context(), id)
	if errors.Is(err, repository.ErrNotFound) {
		writeError(w, http.StatusNotFound, "không tìm thấy sản phẩm")
		return
	}
	if err != nil {
		s.serverError(w, err)
		return
	}

	var payload productPayload
	if !readJSON(w, r, &payload, s.cfg.MaxRequestBody) {
		return
	}
	in, opts, err := payload.toInput()
	if err != nil {
		writeError(w, http.StatusBadRequest, err.Error())
		return
	}
	valid, err := s.categoryExists(r, in.CategoryID)
	if err != nil {
		s.serverError(w, err)
		return
	}
	if !valid {
		writeError(w, http.StatusBadRequest, "danh mục không tồn tại")
		return
	}

	// Keep the existing slug so published links never break on rename.
	in.Slug = existing.Slug

	product, err := s.db.UpdateProduct(r.Context(), id, in)
	if err != nil {
		s.serverError(w, err)
		return
	}
	removed, err := s.db.ReplaceProductImages(r.Context(), product.ID, in.Images)
	if err != nil {
		s.serverError(w, err)
		return
	}
	if err := s.db.SaveProductOptions(r.Context(), product.ID, opts); err != nil {
		s.serverError(w, err)
		return
	}
	for _, path := range removed {
		s.removeStoredImage(r.Context(), path)
	}
	dto := toProductDTO(*product)
	dto.Images = in.Images
	dto.CoverImage = ""
	if len(in.Images) > 0 {
		dto.CoverImage = in.Images[0]
	}
	writeJSON(w, http.StatusOK, dto)
}

func (s *Server) adminDeleteProduct(w http.ResponseWriter, r *http.Request) {
	id, ok := pathID(r, "id")
	if !ok {
		writeError(w, http.StatusBadRequest, "id không hợp lệ")
		return
	}
	images, err := s.db.ListProductImages(r.Context(), id)
	if err != nil {
		s.serverError(w, err)
		return
	}
	err = s.db.DeleteProduct(r.Context(), id)
	if errors.Is(err, repository.ErrNotFound) {
		writeError(w, http.StatusNotFound, "không tìm thấy sản phẩm")
		return
	}
	if err != nil {
		s.serverError(w, err)
		return
	}
	for _, path := range images {
		s.removeStoredImage(r.Context(), path)
	}
	writeJSON(w, http.StatusOK, map[string]any{"deleted": true})
}

func (s *Server) categoryExists(r *http.Request, categoryID *int64) (bool, error) {
	if categoryID == nil {
		return true, nil
	}
	cats, err := s.db.ListCategories(r.Context())
	if err != nil {
		return false, err
	}
	for _, c := range cats {
		if c.ID == *categoryID {
			return true, nil
		}
	}
	return false, nil
}
